/**
 * Application settings: which provider answers, which model, which mentor.
 *
 * Implements: [HC-EXPLICIT-CONFIG-PATHS], [HC-NO-PROVIDER-FALLBACK]
 *
 * Secrets are deliberately absent. Settings are plain JSON on disk; a
 * credential belongs in the encrypted store, never here.
 */

import path from "node:path";
import { readFile } from "node:fs/promises";

import { z } from "zod";

import { providerNameSchema } from "./domain";
import { DEMO_MENTOR_ID } from "./paths";
import { writeFileAtomic } from "./writer";
import {
  isZoomPercent,
  type ZoomPercent,
} from "../shared/types";

export const SETTINGS_FILE = "settings.json";

export const zoomPercentSchema = z.custom<ZoomPercent>(isZoomPercent, {
  message: "Zoom must be one of 80, 90, 100, 110, or 120 percent.",
});

/**
 * A blank model override means "let the provider choose its own default".
 * Storing an empty string instead of omitting the key keeps the form simple.
 */
export const settingsSchema = z.strictObject({
  provider: providerNameSchema.default("copilot"),
  model: z.string().trim().default(""),
  /**
   * What the briefing calls the user. Optional, and empty by default: nothing
   * else in the product knows a name, and a greeting is not worth prompting
   * for one during setup. The screen drops the name when this is blank rather
   * than guessing at a login or a directory name.
   */
  displayName: z.string().trim().max(60).default(""),
  activeMentorId: z.string().trim().min(1).default(DEMO_MENTOR_ID),
  /**
   * Off by default. A notification the user did not ask for is an
   * interruption, and this one is generated by a model reading everything the
   * app knows — that has to be opted into, not discovered.
   */
  briefingEnabled: z.boolean().default(false),
  /**
   * Minutes since local midnight. Stored as a number rather than "12:00"
   * because the comparison is arithmetic and a string would be parsed at every
   * poll — and because a stored string invites a timezone-shaped bug.
   */
  briefingMinute: z.number().int().min(0).max(24 * 60 - 1).default(12 * 60),
  /**
   * Whether the mentor's headline reaches the operating system, or only a
   * fixed generic line does.
   *
   * On by default: a notification saying "your briefing is ready" every day is
   * ignored within a week, which makes the feature pointless. The cost is real
   * and the user is told about it in Settings — macOS may show this on the lock
   * screen and mirror it to a paired iPhone.
   */
  briefingHeadlineInNotification: z.boolean().default(true),
  /**
   * Page zoom percentage. Backward-compatible: files from older releases
   * omit the key and get 100%.
   */
  zoomPercent: zoomPercentSchema.default(100),
});

export type Settings = z.infer<typeof settingsSchema>;

export const DEFAULT_SETTINGS: Settings = settingsSchema.parse({});

export function settingsPath(userDataPath: string): string {
  return path.join(userDataPath, SETTINGS_FILE);
}

/**
 * Settings are a convenience, not a source of truth: a missing or corrupt file
 * falls back to defaults rather than blocking the app on a JSON syntax error
 * the user cannot see. Invalid *values* still fall back, because a provider
 * name that no longer exists must not reach the factory.
 */
export async function loadSettings(userDataPath: string): Promise<Settings> {
  let text: string;
  try {
    text = await readFile(settingsPath(userDataPath), "utf8");
  } catch {
    return DEFAULT_SETTINGS;
  }
  try {
    const result = settingsSchema.safeParse(JSON.parse(text));
    return result.success ? result.data : DEFAULT_SETTINGS;
  } catch {
    return DEFAULT_SETTINGS;
  }
}

export async function saveSettings(
  userDataPath: string,
  input: unknown,
): Promise<Settings> {
  const settings = settingsSchema.parse(input);
  await writeFileAtomic(
    settingsPath(userDataPath),
    `${JSON.stringify(settings, null, 2)}\n`,
  );
  return settings;
}
